"""사용자가 조직에서 어떤 운영자인가.

**활성 사용자면 운영자다** — 기준선은 ``require_active()`` 이고, 키 발급·가드레일 저작은
모든 활성 사용자가 한다. ``ADMIN`` 은 그 위에 얹히는 관문이다: 사용자를 만들고 비활성화하고
역할을 바꾼다.

값이 둘이라 별도 연관이 아니라 필드로 둔다. **자원별 권한**("이 사람은 감사만 읽는다")이
필요해지면 그것은 사용자의 정체성이 아니므로 그때 별도 연관으로 들어온다 — 그 경계를
지금 넘지 않는다 (AGENTS.md 도메인 모델링 원칙 1).
"""

from enum import StrEnum


class Role(StrEnum):
    #: 최고 관리자 — 사용자 관리와 역할 변경.
    ADMIN = "admin"
    #: 일반 운영자 — 키 발급, 가드레일 저작.
    USER = "user"


__all__ = ["Role"]
